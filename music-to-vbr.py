import os
import re
import shutil
import zipfile
import subprocess
from pathlib import Path
from google.colab import files
from mutagen.mp3 import MP3
from mutagen.id3 import ID3, TIT2, TPE1, USLT, APIC
import syncedlyrics
from tqdm import tqdm

def clean_filename(text):
    """Elimina caracteres inválidos para nombres de archivos."""
    return re.sub(r'[\\/*?:"<>|]', "", text).strip()

# ==========================================
# PASO 2: Subir el archivo ZIP con canciones
# ==========================================
print("\nPor favor, sube tu archivo ZIP con las canciones en MP3:")
uploaded = files.upload()

if not uploaded:
    raise ValueError("No se subió ningún archivo. Por favor, vuelve a ejecutar la celda.")

zip_filename = list(uploaded.keys())[0]
extract_dir = "extracted_music"
output_dir = "processed_music"

# Limpiar directorios anteriores para evitar duplicados o basura
if os.path.exists(extract_dir):
    shutil.rmtree(extract_dir)
if os.path.exists(output_dir):
    shutil.rmtree(output_dir)

os.makedirs(extract_dir, exist_ok=True)
os.makedirs(output_dir, exist_ok=True)

with zipfile.ZipFile(zip_filename, 'r') as zip_ref:
    zip_ref.extractall(extract_dir)

print(f"\nArchivo '{zip_filename}' extraído con éxito.")

# ==========================================
# PASO 3: Procesar audio, rescatar carátulas, letras y sincronizar
# ==========================================
mp3_files = list(Path(extract_dir).glob("**/*.mp3"))
print(f"Se encontraron {len(mp3_files)} archivos MP3. Procesando...")

for mp3_path in tqdm(mp3_files):
    file_name_stem = mp3_path.stem
    orig_artist, orig_title, orig_lyrics, orig_artworks = "", "", None, []

    # 1. Leer metadatos, extraer letra y carátula(s) original(es)
    try:
        orig_audio = MP3(mp3_path, ID3=ID3)
        if orig_audio.tags:
            for tag_key, tag_val in orig_audio.tags.items():
                if tag_key.startswith('TPE1'):
                    orig_artist = str(tag_val.text[0])
                elif tag_key.startswith('TIT2'):
                    orig_title = str(tag_val.text[0])
                elif tag_key.startswith('USLT'):
                    orig_lyrics = str(tag_val)
                elif tag_key.startswith('APIC'):
                    orig_artworks.append(tag_val)
    except Exception:
        pass

    # 2. Determinar Artista y Título definitivos
    artist = orig_artist
    title = orig_title if orig_title else file_name_stem

    if (not artist or not orig_title) and " - " in file_name_stem:
        parts = file_name_stem.split(" - ", 1)
        if not artist:
            artist = parts[0].strip()
        if not orig_title:
            title = parts[1].strip()

    clean_artist = clean_filename(artist) if artist else ""
    clean_title = clean_filename(title) if title else clean_filename(file_name_stem)

    if clean_artist:
        final_file_name = f"{clean_artist} - {clean_title}"
        search_query = f"{clean_artist} {clean_title}"
    else:
        final_file_name = clean_title
        search_query = clean_title

    # 3. Convertir MP3 a VBR Clase 0 con nombre limpio
    output_mp3_path = Path(output_dir) / f"{final_file_name}.mp3"
    cmd = ["ffmpeg", "-y", "-i", str(mp3_path), "-q:a", "0", str(output_mp3_path)]
    subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE)

    # 4. Restaurar etiquetas, carátula y letras en el archivo convertido
    try:
        audio_tags = ID3(output_mp3_path)
    except Exception:
        audio_tags = ID3()

    if clean_artist:
        audio_tags.add(TPE1(encoding=3, text=[clean_artist]))
    if clean_title:
        audio_tags.add(TIT2(encoding=3, text=[clean_title]))

    # Reintegrar la carátula original para que funcione la vista previa de Windows
    for art in orig_artworks:
        audio_tags.add(art)

    # Intentar obtener letra sincronizada de internet
    lyrics_saved = False
    try:
        lrc_content = syncedlyrics.search(search_query)
        if lrc_content:
            audio_tags.add(
                USLT(
                    encoding=3,
                    lang='spa',
                    desc='Synced Lyrics',
                    text=lrc_content
                )
            )
            lyrics_saved = True
    except Exception:
        pass

    # Si no se encontró online, conservamos la letra original
    if not lyrics_saved and orig_lyrics:
        audio_tags.add(
            USLT(
                encoding=3,
                lang='spa',
                desc='Lyrics',
                text=orig_lyrics
            )
        )

    audio_tags.save(output_mp3_path)

# ==========================================
# PASO 4: Comprimir resultados y descargar
# ==========================================
result_zip_name = "musica_vbr_sincronizada.zip"
print(f"\nComprimiendo resultados en '{result_zip_name}'...")

with zipfile.ZipFile(result_zip_name, 'w', zipfile.ZIP_DEFLATED) as zip_out:
    for file_to_zip in Path(output_dir).glob("*.mp3"):
        zip_out.write(file_to_zip, file_to_zip.name)

print("¡Proceso finalizado con éxito! Descargando archivo...")
files.download(result_zip_name)

